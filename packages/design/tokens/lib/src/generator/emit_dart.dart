import 'package:design_tokens/src/generator/design_token.dart';

final _segment = RegExp(r'^[A-Za-z][A-Za-z0-9]*$');

/// Renders [tokens] as a Dart library with one constant per token.
///
/// The output is not formatted yet: the generator runs `dart format` on it.
String emitDart(List<DesignToken> tokens) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED by `dart run design_tokens:generate` from')
    ..writeln(
      '// tokens/*.tokens.json. Change the tokens and regenerate instead',
    )
    ..writeln('// of editing this file.')
    ..writeln()
    ..writeln("import 'package:design_tokens/src/shadow_token.dart';")
    ..writeln("import 'package:design_tokens/src/text_token.dart';")
    ..writeln()
    ..writeln('/// Every design token of Birka.')
    ..writeln('abstract final class BirkaTokens {');
  for (final token in tokens) {
    if (token.description case final description?) {
      for (final line in _wrap(description, 74)) {
        buffer.writeln('  /// $line');
      }
      buffer.writeln('  ///');
    }
    buffer
      ..writeln('  /// `${token.name}`${_unit(token.type)}.')
      ..writeln(
        '  static const ${_dartType(token.type)} ${dartName(token)} = '
        '${_dartValue(token)};',
      )
      ..writeln();
  }
  buffer.writeln('}');
  return buffer.toString();
}

/// The constant's name: the token path in lower camel case, with `Ms` after
/// durations.
String dartName(DesignToken token) {
  for (final segment in token.path) {
    if (!_segment.hasMatch(segment)) {
      throw TokenFormatException(
        '${token.name}: use letters and digits in token names',
      );
    }
  }
  final name = [
    token.path.first,
    for (final segment in token.path.skip(1))
      segment[0].toUpperCase() + segment.substring(1),
  ].join();
  return token.type == 'duration' ? '${name}Ms' : name;
}

String _unit(String type) => switch (type) {
  'color' => ' as ARGB',
  'dimension' => ' in logical pixels',
  'duration' => ' in milliseconds',
  _ => '',
};

String _dartType(String type) => switch (type) {
  'color' || 'duration' || 'fontWeight' => 'int',
  'dimension' || 'number' => 'double',
  'fontFamily' => 'List<String>',
  'cubicBezier' => 'List<double>',
  'typography' => 'TextToken',
  'shadow' => 'List<ShadowToken>',
  _ => throw TokenFormatException('no Dart type for $type'),
};

String _dartValue(DesignToken token) => switch (token.value) {
  final int argb when token.type == 'color' => _argb(argb),
  final int whole => '$whole',
  final double number => formatNumber(number),
  final List<String> names => '[${names.map(_quote).join(', ')}]',
  final List<double> points => '[${points.map(formatNumber).join(', ')}]',
  final TypographyValue text =>
    'TextToken(families: [${text.families.map(_quote).join(', ')}], '
        'size: ${formatNumber(text.size)}, weight: ${text.weight}, '
        'letterSpacing: ${formatNumber(text.letterSpacing)}, '
        'lineHeight: ${formatNumber(text.lineHeight)}'
        '${token.extensions['uppercase'] == true ? ', uppercase: true' : ''}'
        '${token.extensions['tabular'] == true ? ', tabular: true' : ''})',
  final List<ShadowValue> layers => '[${layers.map(_shadowToken).join(', ')}]',
  final other => throw TokenFormatException(
    '${token.name}: cannot write ${other.runtimeType} as Dart',
  ),
};

String _shadowToken(ShadowValue layer) =>
    'ShadowToken(color: ${_argb(layer.color)}, '
    'offsetX: ${formatNumber(layer.offsetX)}, '
    'offsetY: ${formatNumber(layer.offsetY)}, '
    'blur: ${formatNumber(layer.blur)}, '
    'spread: ${formatNumber(layer.spread)})';

String _argb(int color) =>
    '0x${color.toRadixString(16).toUpperCase().padLeft(8, '0')}';

/// Splits [text] at spaces into lines of at most [width] characters, so that
/// doc comments stay within the line length.
List<String> _wrap(String text, int width) {
  final lines = <String>[];
  var line = '';
  for (final word in text.split(' ')) {
    if (line.isEmpty) {
      line = word;
    } else if (line.length + 1 + word.length <= width) {
      line = '$line $word';
    } else {
      lines.add(line);
      line = word;
    }
  }
  return [...lines, if (line.isNotEmpty) line];
}

/// Writes [number] without a trailing `.0`, as `22` or `0.14`.
String formatNumber(num number) =>
    number == number.roundToDouble() ? '${number.round()}' : '$number';

String _quote(String text) =>
    "'${text.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";
