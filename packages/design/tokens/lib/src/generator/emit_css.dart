import 'package:design_tokens/src/generator/design_token.dart';
import 'package:design_tokens/src/generator/emit_dart.dart';

const _genericFamilies = {
  'serif',
  'sans-serif',
  'monospace',
  'cursive',
  'fantasy',
  'system-ui',
  'ui-sans-serif',
  'ui-serif',
  'ui-monospace',
  'ui-rounded',
};

final _plainFamily = RegExp(r'^[A-Za-z][A-Za-z0-9-]*$');
final _capital = RegExp('[A-Z]');

/// Renders [tokens] as CSS: custom properties on `:root` and a class per
/// text style.
String emitCss(List<DesignToken> tokens) {
  final buffer = StringBuffer()
    ..writeln(
      '/* GENERATED by `dart run design_tokens:generate` from '
      'tokens/*.tokens.json. */',
    )
    ..writeln(':root {');
  for (final token in tokens.where((t) => t.type != 'typography')) {
    if (token.description case final description?) {
      buffer.writeln('  /* ${description.replaceAll('*/', '* /')} */');
    }
    buffer.writeln('  --${cssName(token)}: ${_cssValue(token)};');
  }
  buffer.writeln('}');
  for (final token in tokens.where((t) => t.type == 'typography')) {
    final text = token.value as TypographyValue;
    buffer.writeln();
    if (token.description case final description?) {
      buffer.writeln('/* ${description.replaceAll('*/', '* /')} */');
    }
    buffer
      ..writeln('.${cssName(token)} {')
      ..writeln('  font-family: ${_families(text.families)};')
      ..writeln('  font-size: ${formatNumber(text.size)}px;')
      ..writeln('  font-weight: ${text.weight};')
      ..writeln('  letter-spacing: ${formatNumber(text.letterSpacing)}px;')
      ..writeln('  line-height: ${formatNumber(text.lineHeight)};');
    if (token.extensions['uppercase'] == true) {
      buffer.writeln('  text-transform: uppercase;');
    }
    if (token.extensions['tabular'] == true) {
      buffer.writeln('  font-variant-numeric: tabular-nums;');
    }
    buffer.writeln('}');
  }
  return buffer.toString();
}

/// The CSS name: the token path in kebab case, such as `color-glass-fill-top`.
String cssName(DesignToken token) => [
  for (final segment in token.path)
    segment.replaceAllMapped(_capital, (m) => '-${m[0]!.toLowerCase()}'),
].join('-');

String _cssValue(DesignToken token) => switch (token.type) {
  'color' => _color(token.value as int),
  'dimension' => '${formatNumber(token.value as double)}px',
  'duration' => '${token.value}ms',
  'number' => formatNumber(token.value as double),
  'fontFamily' => _families(token.value as List<String>),
  'fontWeight' => '${token.value}',
  'cubicBezier' => _cubicBezier(token.value as List<double>),
  final type => throw TokenFormatException('no CSS value for $type'),
};

String _cubicBezier(List<double> points) =>
    'cubic-bezier(${points.map(formatNumber).join(', ')})';

String _color(int argb) {
  final alpha = argb >>> 24;
  final channels = [argb >> 16 & 0xFF, argb >> 8 & 0xFF, argb & 0xFF];
  if (alpha == 0xFF) {
    final hex = channels.map((c) => c.toRadixString(16).padLeft(2, '0'));
    return '#${hex.join()}';
  }
  final opacity = formatNumber(double.parse((alpha / 255).toStringAsFixed(2)));
  return 'rgb(${channels.join(' ')} / $opacity)';
}

String _families(List<String> families) => families
    .map(
      (family) =>
          _genericFamilies.contains(family) || _plainFamily.hasMatch(family)
          ? family
          : '"$family"',
    )
    .join(', ');
