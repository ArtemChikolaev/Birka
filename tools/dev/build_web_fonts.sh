#!/usr/bin/env bash
# Builds the web fonts in packages/design/jaspr/lib/fonts from the variable
# TTFs of the Flutter kit: a WOFF2 subset per alphabet, which browsers fetch
# by `unicode-range`, and fonts.css with their @font-face rules. Run it after
# a change of the fonts. fonttools lives in a temporary Python environment.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
source="$root/packages/design/flutter/fonts"
out="$root/packages/design/jaspr/lib/fonts"
venv="$(mktemp -d)"
trap 'rm -rf "$venv"' EXIT

python3 -m venv "$venv"
"$venv/bin/pip" install --quiet --disable-pip-version-check \
  fonttools==4.68.0 brotli==1.2.1

# Basic Latin and Latin-1, dashes, quotes, the bullet and the ellipsis, the
# euro and ruble signs, the minus and the approximately-equal sign.
latin='U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201E,U+2022,U+2026,U+20AC,U+20BD,U+2212,U+2248'
cyrillic='U+0400-045F,U+0490-0491,U+2116'

rm -rf "$out"
mkdir -p "$out"

# face <family> <weights>
face() {
  for subset in latin cyrillic; do
    unicodes="${!subset}"
    "$venv/bin/pyftsubset" "$source/$1-Variable.ttf" \
      --unicodes="$unicodes" --layout-features+=tnum --flavor=woff2 \
      --output-file="$out/$1-$subset.woff2"
    cat >>"$out/fonts.css" <<EOF
@font-face {
  font-family: "$1";
  src: url("$1-$subset.woff2") format("woff2");
  font-weight: $2;
  font-display: swap;
  unicode-range: ${unicodes//,/, };
}

EOF
  done
  cp "$source/$1-OFL.txt" "$out/"
}

cat >"$out/fonts.css" <<EOF
/* GENERATED by tools/dev/build_web_fonts.sh. */

EOF
face Inter '100 900'
face Manrope '200 800'
echo "Built the web fonts into packages/design/jaspr/lib/fonts."
